"""Bill of materials (CSV + markdown) from the design database."""
import csv, os, collections
from . import design as D

def main():
    comps = D.build()
    groups = collections.OrderedDict()
    for c in comps:
        if c.symbol == "MOUNTING_HOLE" or c.ref.startswith("TP"):
            continue
        key = (c.value, c.footprint, c.mpn)
        groups.setdefault(key, []).append(c)
    rows = []
    for (value, fp, mpn), cs in groups.items():
        refs = ", ".join(sorted((c.ref for c in cs), key=lambda r: (r.rstrip("0123456789"), int("".join(ch for ch in r if ch.isdigit()) or 0))))
        rows.append(dict(qty=len(cs), refs=refs, value=value, footprint=fp, mpn=mpn, description=cs[0].desc))
    rows.sort(key=lambda r: r["refs"])
    out = os.path.join(D.ROOT, "hardware", "bom")
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "bom.csv"), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["qty", "refs", "value", "footprint", "mpn", "description"])
        w.writeheader(); w.writerows(rows)
    with open(os.path.join(out, "bom.md"), "w") as fh:
        fh.write("# Bill of materials\n\n_Generated by `tools/kicad/bom.py`_\n\n| Qty | References | Value | Footprint | MPN / source | Description |\n|---|---|---|---|---|---|\n")
        for r in rows:
            fh.write(f"| {r['qty']} | {r['refs']} | {r['value']} | {r['footprint']} | {r['mpn']} | {r['description']} |\n")
    print(f"BOM: {len(rows)} line items, {sum(r['qty'] for r in rows)} parts")

if __name__ == "__main__":
    main()
