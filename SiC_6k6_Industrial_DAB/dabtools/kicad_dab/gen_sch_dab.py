#!/usr/bin/env python3
"""Generate the DAB KiCad project (symbols, footprints, hierarchical schematic, project file) into 07_KiCad_Schematics/."""
import os, sys, json, shutil
HERE = os.path.dirname(os.path.abspath(__file__)); DAB = os.path.dirname(os.path.dirname(HERE)); REPO = os.path.dirname(DAB)
sys.path.insert(0, REPO); sys.path.insert(0, DAB)
from tools.kicad import gen_schematic as GS, symbols as S, footprints as Fp
from dabtools.kicad_dab import design_dab as D, libs_dab
OUT = os.path.join(DAB, "07_KiCad_Schematics")
os.makedirs(os.path.join(OUT, "lib"), exist_ok=True)
GS.use_design(D)
syms = S.write_library(os.path.join(OUT, "lib", f"{D.LIB}.kicad_sym"), lib=D.LIB, extra=libs_dab.extra_symbols())
fps = Fp.write_library(os.path.join(OUT, "lib", f"{D.LIB}.pretty"), extra=libs_dab.extra_footprints())
# patch titles for this project
GS.title_block.__defaults__ = None
_tb = GS.title_block
def tb(title, sheet_name, page):
    return _tb("SiC 6.6 kW Bidirectional Dual Active Bridge, 800 V / 400 V", sheet_name, page).replace("3 kW, 400 V -> 48 V, 100 kHz, ZVS phase-shifted full bridge", "6.6 kW, 650-850 V <-> 300-450 V, 100 kHz, SiC DAB, SPS/EPS modulation")
GS.title_block = tb
_root = GS.gen_root
def root(root_uuid, sheet_uuids):
    txt = _root(root_uuid, sheet_uuids)
    # replace the PSFB notes block with DAB notes
    import re
    notes = ["SiC 6.6 kW BIDIRECTIONAL DUAL ACTIVE BRIDGE DC-DC CONVERTER - INDUSTRIAL HVDC",
             "HV port 650-850 V DC  |  LV port 300-450 V DC  |  6.6 kW both directions  |  100 kHz  |  SiC 1200 V both bridges",
             "HV bridge 4 x C3M0032120K, LV bridge 4 x C3M0016120K, series inductance 64 uH (4 uH leakage + 60 uH external), n = 2 (E65/3C95, external magnetics module)",
             "Gate drive: 4 x UCC21520 reinforced isolated dual drivers + 8 x isolated +15/-3 V bias; hardware OC/OV comparators -> PROT_DIS -> driver DIS and DSP trip zone",
             "Sensing: AMC1301 isolated amplifiers (V1, V2, I2 shunt), CT on the series inductor (I_L); controller: LAUNCHXL-F280049C BoosterPack headers",
             "Aux: 24 V in -> 12 V (3 A) / 5 V / 3.3 V; CAN (TCAN332), UART service port, precharge contactor outputs and interlock inputs",
             "Sheets: 2 HV port and bridge, 3 LV port and bridge, 4 gate drive and bias, 5 sensing and protection, 6 controller/aux/comms. Generated by dabtools/kicad_dab.",
             "WARNING: HV_* nets up to 850 V DC, LV_* nets up to 450 V DC, gate bias nets ride on the switch nodes. Isolation per 15_Safety_Reliability/01."]
    out = []
    i = 0
    for line in txt.splitlines():
        if line.startswith('  (text "') and i < 8 and "SiC" in line or line.startswith('  (text "') and i < 8:
            # replace in order
            line = re.sub(r'\(text "[^"]*"', '(text ' + GS.q(notes[min(i, 7)]), line, count=1); i += 1
        out.append(line)
    return "\n".join(out)
GS.gen_root = root
comps, sym_uuids = GS.generate(OUT, syms=syms)
# netlist export + check
import subprocess
net = os.path.join(OUT, "netlist_export.net")
r = subprocess.run(["kicad-cli", "sch", "export", "netlist", "--format", "kicadsexpr", "-o", net, os.path.join(OUT, f"{D.PROJECT}.kicad_sch")], capture_output=True, text=True)
print(r.stdout.strip()[-300:], r.stderr.strip()[-300:])
from tools.kicad import check_netlist as CN
CN.D = D
ok = CN.main(net)
print("schematic:", len(comps), "symbols; netlist match:", ok)
