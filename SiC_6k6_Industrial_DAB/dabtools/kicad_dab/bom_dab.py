#!/usr/bin/env python3
"""DAB bill of materials (CSV + Markdown) from the design database. No prices are invented."""
import csv, os, sys, collections, re
HERE = os.path.dirname(os.path.abspath(__file__)); DAB = os.path.dirname(os.path.dirname(HERE)); REPO = os.path.dirname(DAB)
sys.path.insert(0, REPO); sys.path.insert(0, DAB)
from dabtools.kicad_dab import design_dab as D

RATINGS = {  # value pattern -> (rating/derating note, datasheet or manufacturer page)
    "C3M0032120K": ("1200 V, 32 mOhm, Tj 175 C; used at 850 V (71 %), Tj < 70 C calc.", "https://www.wolfspeed.com/c3m0032120k/"),
    "C3M0016120K": ("1200 V, 16 mOhm; used at 450 V (38 %)", "https://www.wolfspeed.com/c3m0016120k/"),
    "UCC21520DW": ("5.7 kVrms reinforced, 4 A/6 A, VDD 25 V max; used at 18 V", "https://www.ti.com/product/UCC21520"),
    "R12P21503D": ("2 W, 5.2 kVDC isolation (basic class) - open item 15.1", "https://recom-power.com/"),
    "AMC1301": ("+/-250 mV, 7 kVpk reinforced", "https://www.ti.com/product/AMC1301"),
    "ISO 5V/5V 1W SIP-7": ("1 W isolated 5 V module, SIP-7 outline, reinforced-rated part to be selected (open item 15.1)", ""),
    "LM393": ("36 V, open collector", "https://www.ti.com/product/LM393"),
    "TLV9062": ("5.5 V RRIO 10 MHz", "https://www.ti.com/product/TLV9062"),
    "74HC32": ("2-6 V", "https://www.ti.com/product/SN74HC32"),
    "TCAN332": ("3.3 V CAN FD 5 Mbit/s", "https://www.ti.com/product/TCAN332"),
    "TSR 3-24120": ("3 A, 4.6-36 V in", "https://www.tracopower.com/"),
    "TSR 1-2450": ("1 A", "https://www.tracopower.com/"),
    "AMS1117-3.3": ("1 A LDO", ""),
    "ULN2003A": ("50 V / 500 mA per channel", "https://www.ti.com/product/ULN2003A"),
    "PC817": ("5 kVrms, CTR 50-600 %", ""),
    "20uF/1100V": ("film, 1100 V DC; used at 850 V (77 %)", "https://www.tdk-electronics.tdk.com/"),
    "30uF/700V": ("film, 700 V DC; used at 450 V (64 %)", "https://www.tdk-electronics.tdk.com/"),
    "100nF/1kV": ("X7T 1 kV MLCC; used at 850 V (85 %) - consider 2 kV part", ""),
    "220nF/630V": ("X7T 630 V MLCC; used at 450 V (71 %)", ""),
    "4.7nF Y1": ("Y1 safety capacitor, 500 Vac", "https://www.vishay.com/"),
    "1mR": ("0.5 % 2 W shunt", "https://www.vishay.com/"),
    "680k/2W": ("2512, 2 W; 212 V per resistor (voltage rating 500 V)", ""),
    "1M/2W": ("2512, 2 W; 225 V per resistor", ""),
}
def rating_for(c):
    for k, v in RATINGS.items():
        if k in c.value or k in c.mpn: return v
    return ("", "")

def main():
    comps = D.build()
    groups = collections.OrderedDict()
    for c in comps:
        if c.symbol == "MOUNTING_HOLE" or c.ref.startswith("TP"): continue
        groups.setdefault((c.value, c.footprint, c.mpn), []).append(c)
    rows = []
    for (value, fp, mpn), cs in groups.items():
        refs = ", ".join(sorted((c.ref for c in cs), key=lambda r: (r.rstrip("0123456789"), int("".join(ch for ch in r if ch.isdigit()) or 0))))
        mfr = mpn.split(" ")[0] if mpn else ""
        rating, ds = rating_for(cs[0])
        flags = []
        if not cs[0].pin_verified: flags.append("PINOUT TO VERIFY")
        if "verify" in mpn.lower() or "class" in mpn.lower() or "custom" in mpn.lower() or not mpn: flags.append("PART SELECTION TO VERIFY")
        rows.append(dict(qty=len(cs), refs=refs, value=value, package=fp, manufacturer=mfr, mpn=mpn.replace(mfr, "").strip(" ,") if mfr else "",
                         rating=rating, datasheet=ds, unit_cost="not verified", alternatives="", procurement=" ; ".join(flags), description=cs[0].desc))
    rows.sort(key=lambda r: r["refs"])
    out = os.path.join(DAB, "16_BOM"); os.makedirs(out, exist_ok=True)
    cols = ["qty", "refs", "value", "package", "manufacturer", "mpn", "rating", "datasheet", "unit_cost", "alternatives", "procurement", "description"]
    with open(os.path.join(out, "bom.csv"), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=cols); w.writeheader(); w.writerows(rows)
    with open(os.path.join(out, "bom.md"), "w") as fh:
        fh.write("# 16 - Bill of materials (DAB power board, rev A)\n\n_Generated by `dabtools/kicad_dab/bom_dab.py`. Unit costs are deliberately not given (no verified quotes); "
                 "items marked PINOUT TO VERIFY / PART SELECTION TO VERIFY need datasheet confirmation before ordering. External magnetics (transformer, series inductor), heatsinks, fans, the LaunchPad and the enclosure are listed in `off_board_items.md`._\n\n")
        fh.write("| Qty | Refs | Value | Package | Manufacturer | MPN | Rating / derating | Procurement flags | Description |\n|---|---|---|---|---|---|---|---|---|\n")
        for r in rows:
            fh.write(f"| {r['qty']} | {r['refs']} | {r['value']} | {r['package']} | {r['manufacturer']} | {r['mpn']} | {r['rating']} | {r['procurement']} | {r['description']} |\n")
    with open(os.path.join(out, "off_board_items.md"), "w") as fh:
        fh.write("# Off-board items\n\n| Item | Specification | Reference |\n|---|---|---|\n"
                 "| T1 main transformer | 2 x E65/32/27 3C95, 28:14, litz, reinforced tape | 06_Magnetics |\n| L1 series inductor | 2 x E55/28/21 3C95 gapped, 60 uH | 06_Magnetics |\n"
                 "| CT1 core | ferrite toroid 1:100 (Magnetics ZW42908TC class) | 06_Magnetics |\n| Controller | TI LAUNCHXL-F280049C | 10_Firmware |\n"
                 "| Heatsinks | 2 x extruded 150 x 60 x 40 mm, 0.22 K/W at 3 m/s | 13_Thermal_Analysis |\n| Fans | 2 x 80 mm 24 V, 60 m3/h | 13_Thermal_Analysis |\n"
                 "| HV fuse | 16 A / 1000 V semiconductor fuse, 14x51 body (Bussmann FWP class, verify) | 15_Safety_Reliability |\n| LV fuse | 32 A / 700 V semiconductor fuse (verify) | 15_Safety_Reliability |\n"
                 "| Precharge | contactor + 100 Ohm / 100 W resistor per port (system) | 00_Requirements APP-05 |\n| EMI filter | 2-stage DM/CM per port | 14_EMI_EMC |\n| Enclosure | IP20 module, PE bonded | 15_Safety_Reliability |\n")
    print(f"BOM: {len(rows)} line items, {sum(r['qty'] for r in rows)} parts; flagged: {sum(1 for r in rows if r['procurement'])}")

if __name__ == "__main__":
    main()
