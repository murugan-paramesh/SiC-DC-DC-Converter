#!/usr/bin/env python3
"""
Generate an ngspice netlist of the DAB power stage with behavioural SiC switches (Ron/Roff
switch + body diode + Coss) and the designed L, n, C1, C2, run it in batch mode and
post-process: ZVS check (drain voltage at turn-on), inductor current, power.
Output: 05_Simulation/spice/dab_sps.cir, dab_sps.raw/csv, img/spice_*.png
"""
import os, sys, json, math, subprocess
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE); sys.path.insert(0, ROOT)
from dabtools.dab.devices import DEVICES
V = json.load(open(os.path.join(ROOT, "04_Design_Calculations", "design_values.json")))
L, n, fs = V["L"], V["spec"]["n"], V["spec"]["fs"]
phi = V["phi_nom"]; Ts = 1 / fs
V1, V2 = 800.0, 400.0
d1, d2 = DEVICES[V["dev1"]], DEVICES[V["dev2"]]
td = V["t_dead"]
SP = os.path.join(HERE, "spice"); os.makedirs(SP, exist_ok=True)

def bridge(name, Vdc_node, gnd, out_a, out_b, Ron, Coss, delay, dead):
    """Four switches S_name_{1..4}: 1 = A high, 2 = A low, 3 = B high, 4 = B low."""
    lines = []
    tpw = Ts / 2 - dead
    for k, (nd, ns, dly) in enumerate(((Vdc_node, out_a, 0.0), (out_a, gnd, Ts / 2), (out_b, gnd, 0.0), (Vdc_node, out_b, Ts / 2)), start=1):
        g = f"g{name}{k}"
        lines.append(f"V{g} {g} 0 PULSE(0 1 {delay + dly + dead:.4e} 5n 5n {tpw:.4e} {Ts:.4e})")
        lines.append(f"S{name}{k} {nd} {ns} {g} 0 SW_{name}")
        lines.append(f"D{name}{k} {ns} {nd} DBODY_{name}")
        lines.append(f"C{name}{k} {nd} {ns} {Coss:.3e}")
    lines.append(f".model SW_{name} SW(Ron={Ron} Roff=1e7 Vt=0.5 Vh=0.1)")
    lines.append(f".model DBODY_{name} D(Is=1e-12 N=2.0 Rs=0.01 Cjo=1e-12)")
    return "\n".join(lines)

net = f"""* 6.6 kW SiC DAB, SPS phi = {math.degrees(phi):.1f} deg, generated by gen_spice.py
.param L={L:.3e} n={n} fs={fs}
V1 vhv 0 DC {V1}
R1s vhv vhv_i 0.3
C1 vhv_i 0 {V['dclink']['C1']:.3e} ic={V1}
* LV port: battery-like source through 0.1 Ohm (bidirectional sink), link capacitor
V2 vlv 0 DC {V2}
R2s vlv vlv_i 0.1
C2 vlv_i 0 {V['dclink']['C2']:.3e} ic={V2}
{bridge('A', 'vhv_i', '0', 'a', 'b', d1['Rds_150'], d1['Coss_er'], 0.0, td)}
* series inductor + ideal transformer (behavioural: Vp = n*Vs, Is = n*Ip)
Lser a p1 {{L}}
Ep p1 p2 value={{ {n}*v(s1,s2) }}
Rp p2 b 20m
Gs s2 s1 value={{ {n}*i(Ep) }}
Rs1 s1 0 1e9
Rs2 s2 0 1e9
{bridge('B', 'vlv_i', '0', 's1', 's2', d2['Rds_150'], d2['Coss_er'], phi/(2*math.pi)*Ts, td)}
.tran 2n {40*Ts:.3e} {36*Ts:.3e} 2n uic
.control
run
set wr_singlescale
set wr_vecnames
wrdata {os.path.join(SP, 'dab_sps.csv')} v(a,b) v(s1,s2) i(Lser) v(a) v(s1) v(vhv_i) v(vlv_i) i(V1) i(V2)
quit
.endc
.end
"""
open(os.path.join(SP, "dab_sps.cir"), "w").write(net)
r = subprocess.run(["ngspice", "-b", os.path.join(SP, "dab_sps.cir")], capture_output=True, text=True, timeout=1800)
log = r.stdout + r.stderr
open(os.path.join(SP, "ngspice.log"), "w").write(log)
csv = os.path.join(SP, "dab_sps.csv")
if not os.path.exists(csv):
    print("ngspice failed:\n", log[-3000:]); sys.exit(1)
data = np.loadtxt(csv, skiprows=1)
t = data[:, 0]; vab, vs, iL, va, vs1, vhv, vlv, i1, i2 = [data[:, k] for k in range(1, 10)]
import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
fig, ax = plt.subplots(3, 1, figsize=(7, 7), sharex=True)
tt = (t - t[0]) * 1e6
ax[0].plot(tt, vab, label="v_AB (HV bridge)"); ax[0].plot(tt, n * vs, label="n v_LV bridge"); ax[0].legend(); ax[0].set_ylabel("V")
ax[1].plot(tt, iL); ax[1].set_ylabel("i_L (A)")
ax[2].plot(tt, va, label="v(A) leg node"); ax[2].plot(tt, vs1, label="v(S1) LV leg node"); ax[2].legend(); ax[2].set_ylabel("V"); ax[2].set_xlabel("us")
[a.grid(alpha=0.3) for a in ax]; fig.suptitle("ngspice switched model, SPS, 800/400 V, dead time %.0f ns" % (td * 1e9)); fig.tight_layout()
fig.savefig(os.path.join(HERE, "img", "spice_sps_waveforms.png"), dpi=130); plt.close(fig)
# metrics
P_in = float(-np.mean(vhv * i1)); P_out = float(np.mean(vlv * i2)) if False else float(-np.mean(vlv * i2))
# ZVS check: sample the switch voltage 10 ns before each gate turn-on (gate timing known from the PULSE sources)
def zvs_check(v_node, v_rail, t_on_list, Vdc):
    worst = 0.0
    for t_on in t_on_list:
        k = np.searchsorted(t, t_on - 10e-9)
        if 0 < k < len(t):
            vds = abs(v_rail[k] - v_node[k])
            worst = max(worst, vds / Vdc)
    return worst
t0, t1 = t[0], t[-1]
# A1 (HV high side, node a): on at delay 0 + td + m Ts ; A2 (low side): td + Ts/2 + m Ts
mA = np.arange(math.floor(t0 / Ts) - 1, math.ceil(t1 / Ts) + 1)
on_A1 = [m * Ts + td for m in mA if t0 < m * Ts + td < t1]
on_A2 = [m * Ts + Ts / 2 + td for m in mA if t0 < m * Ts + Ts / 2 + td < t1]
delB = phi / (2 * math.pi) * Ts
on_B1 = [m * Ts + delB + td for m in mA if t0 < m * Ts + delB + td < t1]
on_B2 = [m * Ts + delB + Ts / 2 + td for m in mA if t0 < m * Ts + delB + Ts / 2 + td < t1]
zvs = dict(A1_vds_at_turnon_pu=zvs_check(va, vhv, on_A1, V1), A2_vds_at_turnon_pu=zvs_check(va, np.zeros_like(va), on_A2, V1),
           B1_vds_at_turnon_pu=zvs_check(vs1, vlv, on_B1, V2), B2_vds_at_turnon_pu=zvs_check(vs1, np.zeros_like(vs1), on_B2, V2))
res = dict(P_in_W=P_in, iL_pk=float(np.abs(iL).max()), iL_rms=float(np.sqrt(np.mean(iL ** 2))),
           analytic_Irms=V["nominal"]["Irms1"], analytic_Ipk=V["nominal"]["Ipk1"], dead_time_ns=td * 1e9,
           phase_loss_deg_equivalent=360 * fs * td, zvs=zvs, note="vds/Vdc at turn-on < 0.05 = ZVS")
json.dump(res, open(os.path.join(SP, "spice_results.json"), "w"), indent=1)
print(json.dumps(res, indent=1))
