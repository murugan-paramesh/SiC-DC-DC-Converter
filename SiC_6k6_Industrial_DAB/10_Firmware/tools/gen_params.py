#!/usr/bin/env python3
"""Generate src/dab_params.h from the design and control parameter files (single source of truth)."""
import json, os, math
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE))
V = json.load(open(os.path.join(ROOT, "04_Design_Calculations", "design_values.json")))
C = json.load(open(os.path.join(ROOT, "11_Control_Algorithms", "control_params.json")))
L = C["limits"]
h = f"""/* AUTO-GENERATED by tools/gen_params.py - do not edit. Source: 04_Design_Calculations/design_values.json, 11_Control_Algorithms/control_params.json */
#ifndef DAB_PARAMS_H
#define DAB_PARAMS_H
#define DAB_FSW_HZ          ({V['spec']['fs']:.1f}f)
#define DAB_TS_S            ({1/V['spec']['fs']:.9e}f)
#define DAB_L_H             ({V['L']:.6e}f)       /* series inductance, HV referred */
#define DAB_N_RATIO         ({V['spec']['n']:.4f}f)   /* N1/N2 */
#define DAB_P_RATED_W       ({V['spec']['P']:.1f}f)
#define DAB_P_MAX_W         ({1.1*V['spec']['P']:.1f}f)
#define DAB_V2_REF_V        ({V['spec']['V2_nom']:.1f}f)
#define DAB_PHI_MAX_RAD     ({math.radians(C['phi_max_deg']):.6f}f)
#define DAB_PHI_DEAD_COMP   ({C['phi_dead_comp_rad']:.6e}f)
#define DAB_D_MIN           ({C['D_min']:.3f}f)
#define DAB_V2_FLOOR_V      ({C['V2_floor']:.1f}f)
#define DAB_KP_W_PER_V      ({C['kp']:.6e}f)
#define DAB_KI_W_PER_VS     ({C['ki']:.6e}f)
#define DAB_SOFT_START_S    ({C['soft_start_s']:.4f}f)
#define DAB_SLEW_W_PER_S    ({C['slew_W_per_s']:.3e}f)
#define DAB_T_DEAD_S        ({V['t_dead']:.3e}f)
#define LIM_V1_OV_V         ({L['v1_ov']:.1f}f)
#define LIM_V1_UV_V         ({L['v1_uv']:.1f}f)
#define LIM_V2_OV_V         ({L['v2_ov']:.1f}f)
#define LIM_V2_UV_V         ({L['v2_uv']:.1f}f)
#define LIM_I_PK_HV_A       ({L['i_pk_hv']:.2f}f)
#define LIM_T_MAX_C         ({L['T_max']:.1f}f)
#endif
"""
open(os.path.join(os.path.dirname(HERE), "src", "dab_params.h"), "w").write(h)
print("dab_params.h written")
