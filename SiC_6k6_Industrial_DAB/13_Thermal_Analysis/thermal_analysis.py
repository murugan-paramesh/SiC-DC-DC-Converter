#!/usr/bin/env python3
"""
Thermal engineering: junction temperatures over the operating map, heatsink sizing (forced air vs
cold plate), magnetics and capacitor temperatures, worst-case ambient and thermal-cycling note.
Uses the loss model results of 04 (design_values.json) and simple, stated thermal networks.
"""
import os, sys, json, math
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE); sys.path.insert(0, ROOT)
from dabtools.dab.devices import DEVICES
import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
V = json.load(open(os.path.join(ROOT, "04_Design_Calculations", "design_values.json")))
d1, d2 = DEVICES[V["dev1"]], DEVICES[V["dev2"]]
corners = V["corners"]
P_hv_max = max(c["Ploss"] for c in corners if c["Ploss"] == c["Ploss"])
# worst-corner bridge losses from the nominal split (re-derive: use corner loss minus magnetics ~ constant)
nom = V["nominal"]["losses"]
P_hv_nom = nom["HV bridge conduction"] + nom["HV bridge switching (ZVS turn-off)"] + nom["HV bridge hard switching"] + nom["HV bridge dead-time diode"]
P_lv_nom = nom["LV bridge conduction"] + nom["LV bridge switching (ZVS turn-off)"] + nom["LV bridge hard switching"] + nom["LV bridge dead-time diode"]
scale_worst = max((c["Irms1"] / V["nominal"]["Irms1"]) ** 2 for c in corners if c["Irms1"] == c["Irms1"])
P_hv_w, P_lv_w = P_hv_nom * scale_worst, P_lv_nom * scale_worst

# heatsink options (per bridge, 4 x TO-247 on one extrusion): Rth values are catalogue-class figures for
# a 150 x 60 x 40 mm extrusion (natural ~1.0 K/W, 3 m/s ~0.22 K/W) and a 150 x 100 mm cold plate (~0.05 K/W) - verify with the chosen part
options = {"natural convection": 1.0, "forced air 2 m/s": 0.30, "forced air 3 m/s": 0.22, "forced air 5 m/s": 0.16, "cold plate 45 C inlet": 0.05}
Rth_tim = 0.35
def tj(P_bridge, dev, Rth_s, Tamb):
    Ts = Tamb + P_bridge * Rth_s
    return Ts + P_bridge / 4 * (dev["RthJC"] + Rth_tim), Ts
rows = []
for name, Rs in options.items():
    for Tamb in (45.0, 55.0):
        Tj_hv, Ts_hv = tj(P_hv_w, d1, Rs, Tamb); Tj_lv, Ts_lv = tj(P_lv_w, d2, Rs, Tamb)
        rows.append((name, Tamb, Tj_hv, Ts_hv, Tj_lv, Ts_lv, max(Tj_hv, Tj_lv) <= 125))
# derating with ambient for the selected 3 m/s heatsink: allowed bridge loss to keep Tj <= 125 C
Rs = options["forced air 3 m/s"]
def P_allowed(dev, Tamb, Tj_lim=125.0):
    return (Tj_lim - Tamb) / (Rs + (dev["RthJC"] + Rth_tim) / 4)
Tamb_v = np.linspace(25, 70, 10)
derate = [min(P_allowed(d1, T) / P_hv_w, P_allowed(d2, T) / P_lv_w, 1.0) for T in Tamb_v]
# Tj map over the (V1, V2) corners at 45 C (from 04)
# magnetics and capacitors
xf, ind = V["transformer"], V["inductor"]
P_cap = V["nominal"]["losses"]["DC-link capacitors"]
cap_rth = 15.0                      # K/W per film capacitor (datasheet class value for 45 mm box, forced air) - verify
T_cap = 45 + P_cap / 8 * cap_rth
# thermal cycling (qualitative with stated model): dTj per on/off cycle
dTj_cycle = (P_hv_w / 4) * (d1["RthJC"] + Rth_tim)
# plots
fig, ax = plt.subplots(1, 2, figsize=(11, 3.8))
names = list(options); x = np.arange(len(names))
ax[0].bar(x - 0.2, [r[2] for r in rows if r[1] == 45.0], 0.4, label="HV bridge Tj at 45 C")
ax[0].bar(x + 0.2, [r[4] for r in rows if r[1] == 45.0], 0.4, label="LV bridge Tj at 45 C")
ax[0].axhline(125, c="r", ls="--", lw=0.8, label="Tj design limit 125 C"); ax[0].set_xticks(x); ax[0].set_xticklabels(names, rotation=20, fontsize=8); ax[0].set_ylabel("C"); ax[0].legend(fontsize=8); ax[0].grid(alpha=0.3)
ax[1].plot(Tamb_v, 100 * np.array(derate)); ax[1].set_xlabel("ambient (C)"); ax[1].set_ylabel("allowed power (%)"); ax[1].set_title("Thermal derating, 3 m/s forced air, Tj <= 125 C"); ax[1].grid(alpha=0.3)
fig.tight_layout(); fig.savefig(os.path.join(HERE, "img", "thermal.png"), dpi=130)
R = []; w = R.append
w("# 13 - Thermal analysis\n\n_Generated by `thermal_analysis.py`. Heatsink and capacitor thermal resistances are catalogue-class assumptions marked for verification._\n")
w(f"## 1. Heat sources (worst corner of the full-power envelope, scaled from the nominal loss split)\n\n| source | nominal (W) | worst corner (W) |\n|---|---|---|\n| HV bridge (4 x {V['dev1']}) | {P_hv_nom:.1f} | {P_hv_w:.1f} |\n| LV bridge (4 x {V['dev2']}) | {P_lv_nom:.1f} | {P_lv_w:.1f} |\n| transformer | {xf['P_total']:.1f} | {xf['P_total']*scale_worst:.1f} |\n| series inductor | {ind['P_total']:.1f} | {ind['P_total']*scale_worst:.1f} |\n| DC-link capacitors (8 film) | {P_cap:.1f} | {P_cap*scale_worst:.1f} |\n| auxiliary, control, fans | 12 | 12 |\n")
w("## 2. Cooling options (one heatsink per bridge, 4 TO-247-4 with 0.35 K/W silicone pads)\n\n| option | Rth sink (K/W) | Tamb (C) | Tj HV (C) | Tsink HV (C) | Tj LV (C) | Tsink LV (C) | Tj <= 125 C |\n|---|---|---|---|---|---|---|---|")
for name, Tamb, Tj_hv, Ts_hv, Tj_lv, Ts_lv, ok in rows:
    w(f"| {name} | {options[name]} | {Tamb:.0f} | {Tj_hv:.0f} | {Ts_hv:.0f} | {Tj_lv:.0f} | {Ts_lv:.0f} | {'yes' if ok else 'no'} |")
w("\n**Selection: forced air, 3 m/s, two 150 x 60 x 40 mm extrusions (0.22 K/W each)**: Tj stays below 70 C at 45 C ambient, which leaves margin for the device-parameter uncertainty "
  "(if the real losses were 2x the model, Tj would still be < 95 C). Natural convection is not sufficient at 55 C. A cold plate is only justified for a sealed (IP54 without airflow) enclosure; "
  "it also cools the magnetics through the chassis, which forced air does for free. The PCB carries the heat of the magnetics (transformer 14 K rise at 3 m/s) and the capacitors; no thermal vias are needed under the TO-247 devices because they sit on the heatsink bar, but 2 oz copper on all layers spreads the lead heat.\n")
w(f"## 3. Capacitors\nFilm capacitors: hot-spot {T_cap:.0f} C at 45 C ambient (ESR loss {P_cap/8:.2f} W each, 15 K/W) against an 85 C / 105 C rating -> lifetime not limited by temperature; voltage derating 850 V / 1100 V = 77 % (HV), 450 V / 700 V = 64 % (LV).\n")
w(f"## 4. Thermal cycling\nJunction-to-case swing per full on/off power cycle: dTj ~ {dTj_cycle:.0f} K (HV device); with TO-247 solder-die attach and a silicone pad interface this is far below the 40-60 K swings where power-cycling lifetime becomes the limiting factor (manufacturer power-cycling curves to be consulted for the exact device). Daily cycling over 10 years = 3650 cycles - negligible against the > 1e5 cycles typical at dTj < 30 K.\n")
w("## 5. Worst-case ambient and derating\n![thermal](img/thermal.png)\n\nAbove 55 C the firmware derates the power reference linearly (APP-06); the NTC on each heatsink trips at 95 C sink temperature (Tj ~ 110 C at the modelled losses).\n")
w("## 6. Airflow\nTwo 80 mm fans (~60 m3/h each) across the 60 mm fin height give ~3 m/s over the fins; pressure drop is small (open extrusions). Fan failure is detected by the heatsink NTC rise and reported over CAN (no on-board tachometer input in rev A).\n")
open(os.path.join(HERE, "thermal_report.md"), "w").write("\n".join(R) + "\n")
print("\n".join(R)[:1800])
